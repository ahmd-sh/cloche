def svg(with_ground=True):
    defs, body = [], []
    for i, s in enumerate(shapes):
        if "fill" in s:
            kind, g, stops = s["fill"]
            sts = "".join(f'<stop offset="{o}" stop-color="{color(c)[0]}" stop-opacity="{color(c)[1]:.3f}"/>' for o, c in stops)
            if kind == "linear":
                defs.append(f'<linearGradient id="g{i}" gradientUnits="userSpaceOnUse" x1="{g[0]:.2f}" y1="{g[1]:.2f}" x2="{g[2]:.2f}" y2="{g[3]:.2f}">{sts}</linearGradient>')
            else:
                defs.append(f'<radialGradient id="g{i}" gradientUnits="userSpaceOnUse" cx="{g[0]:.2f}" cy="{g[1]:.2f}" r="{g[2]:.2f}">{sts}</radialGradient>')
            body.append(f'<path d="{s["d"]}" fill="url(#g{i})"/>')
        else:
            c, a = color(s["stroke"])
            body.append(f'<path d="{s["d"]}" fill="none" stroke="{c}" stroke-opacity="{a:.3f}" stroke-width="{s["width"]}" stroke-linecap="round"/>')
    ground = ""
    if with_ground:
        lines = "".join(f'<path d="M{i},0V108M0,{i}H108" stroke="{"#26FFFFFF" if i % 27 == 0 else "#14FFFFFF"}" stroke-width="{0.7 if i % 27 == 0 else 0.5}"/>' for i in range(0, 109, 9))
