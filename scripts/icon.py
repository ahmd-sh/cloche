def anim(target, props, pad="    "):
    out = [f'{pad}<target android:name="{target}">', f'{pad}    <aapt:attr name="android:animation">', f'{pad}        <set android:ordering="together">']
    for prop, start, dur, keys in props:
        kf = "\n".join(f'{pad}                    <keyframe android:fraction="{f}" android:value="{v}" />' for f, v in keys)
        out += [f'{pad}            <objectAnimator android:startOffset="{start}" android:duration="{dur}" android:interpolator="@android:interpolator/fast_out_slow_in">',
                f'{pad}                <propertyValuesHolder android:propertyName="{prop}" android:valueType="floatType">', kf,
                f'{pad}                </propertyValuesHolder>', f'{pad}            </objectAnimator>']
    out += [f'{pad}        </set>', f'{pad}    </aapt:attr>', f'{pad}</target>']
    return "\n".join(out)

