import math, sys

def ellipse(cx, cy, rx, ry):
    return f"M{cx-rx:.2f},{cy:.2f}a{rx:.2f},{ry:.2f} 0 1,0 {2*rx:.2f},0a{rx:.2f},{ry:.2f} 0 1,0 {-2*rx:.2f},0z"

def poly(*pts):
    return "M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in pts) + "z"

def rrect(x, y, w, h, r):
    f = lambda v: f"{v:.2f}".rstrip("0").rstrip(".")
    return (f"M{f(x+r)},{f(y)}H{f(x+w-r)}A{f(r)},{f(r)} 0 0 1 {f(x+w)},{f(y+r)}V{f(y+h-r)}A{f(r)},{f(r)} 0 0 1 {f(x+w-r)},{f(y+h)}"
            f"H{f(x+r)}A{f(r)},{f(r)} 0 0 1 {f(x)},{f(y+h-r)}V{f(y+r)}A{f(r)},{f(r)} 0 0 1 {f(x+r)},{f(y)}z")

def lin(x1, y1, x2, y2, *stops): return ("linear", (x1, y1, x2, y2), stops)
def rad(cx, cy, r, *stops): return ("radial", (cx, cy, r), stops)

def along(d, side):
    ax, ay = 50.0, 75.5
    ux, uy = -math.sqrt(.5), math.sqrt(.5)
    px, py = math.sqrt(.5), math.sqrt(.5)
    return (ax + ux*d + px*side, ay + uy*d + py*side)

